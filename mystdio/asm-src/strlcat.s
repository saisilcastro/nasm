SECTION .text
GLOBAL StrlCat
EXTERN StrLen
EXTERN StrnCat
StrlCat:
	PUSH R10
	PUSH R11
	CALL StrLen
	MOV R11, RAX
	PUSH RDI
	MOV RDI, RSI
	CALL StrLen
	POP RDI
	MOV R10, RAX
	CMP R11, RDX
	JGE size
	ADD RDI, R11
	SUB RDX, R11
	DEC RDX
	CALL StrnCat
	LEA RAX, [R10 + R11]
	POP R11
	POP R10
	RET
size:
	LEA RAX, [RDX + R10]
	POP R11
	POP R10
	RET
