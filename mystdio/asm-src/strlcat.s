SECTION .TEXT
GLOBAL StrlCat
EXTERN StrLen
EXTERN StrnCat
StrlCat:
	PUSH R10
	PUSH R11
	CALL StrLen
	MOV R11, RAX
	PUSH RCX
	MOV RCX, RDX
	CALL StrLen
	POP RCX
	MOV R10, RAX
	CMP R11, R8
	JGE size
	ADD RCX, R11
	SUB R8, R11
	DEC R8
	CALL StrnCat
	LEA RAX, [R10 + R11]
	POP R11
	POP R10
	RET
size:
	LEA RAX, [R8 + R10]
	POP R11
	POP R10
	RET
